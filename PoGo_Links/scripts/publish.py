#!/usr/bin/env python3
"""Publish Bart's Pokémon GO link pages from Google Drive to GitHub Pages.

Copies every .html in Drive "Other/Pokémon GO/web pages w links/" (top level only, so "backup …/" folders are
skipped) into PoGo_Links/, removes pages that are no longer in Drive, rebuilds PoGo_Links/index.html (the list,
newest first), then commits and pushes. Pages are copied byte for byte: each one already embeds its GPX and keeps
its Done ticks under its own localStorage key.

Usage (from anywhere):
  python3 -I PoGo_Links/scripts/publish.py           # publish, commit and push
  python3 -I PoGo_Links/scripts/publish.py -n        # dry run: show what would change, touch nothing
  python3 -I PoGo_Links/scripts/publish.py --no-push # write and commit, don't push
  python3 -I PoGo_Links/scripts/publish.py --src DIR # another source folder
Called by the coord-link-page skill after it writes a page (2026-10-10).
"""
import argparse
import datetime
import glob
import html
import json
import os
import re
import subprocess
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(HERE)                      # PoGo_Links/
REPO = os.path.dirname(OUT)                      # BartmanEH.github.io/
DRIVE_GLOB = os.path.expanduser("~/Library/CloudStorage/GoogleDrive-*/My Drive/Other/Pokémon GO/web pages w links")


def git(*args, check=True):
    r = subprocess.run(["git", "-C", REPO, *args], capture_output=True, text=True)
    if check and r.returncode:
        sys.exit(f"git {' '.join(args)} failed:\n{r.stderr.strip()}")
    return r.stdout.strip()


def find_source(arg):
    if arg:
        return arg
    hits = [p for p in glob.glob(DRIVE_GLOB) if os.path.isdir(p)]
    if len(hits) != 1:
        sys.exit(f"Can't find the Drive folder (matches: {len(hits)}). Pass --src.")
    return hits[0]


def page_info(path):
    """Title and number of places, read from the page itself."""
    s = open(path, encoding="utf-8").read()
    m = re.search(r"<title>(.*?)</title>", s, re.S)
    title = html.unescape(m.group(1).strip()) if m else os.path.splitext(os.path.basename(path))[0]
    count = None
    m = re.search(r"var D\s*=\s*", s)                 # coord-link-page pages
    if m:
        try:
            count = len(json.JSONDecoder().raw_decode(s[m.end():])[0].get("points", []))
        except ValueError:
            pass
    else:                                              # Pokémap quest Export pages
        m = re.search(r"var POINTS\s*=\s*", s)
        if m:
            try:
                count = len(json.JSONDecoder().raw_decode(s[m.end():])[0])
            except ValueError:
                pass
    return title, count


def build_index(pages):
    """pages: list of (file name, title, count, mtime), newest first."""
    rows = []
    for name, title, count, mtime in pages:
        bits = []
        if count is not None:
            bits.append(f"{count} place{'s' if count != 1 else ''}")
        bits.append("updated " + datetime.date.fromtimestamp(mtime).isoformat())
        bits.append(os.path.splitext(name)[0])        # file name: tells apart pages with generic titles
        rows.append(
            f'  <a class="row" href="./{html.escape(name, quote=True)}">'
            f'<span class="t">{html.escape(title)}</span>'
            f'<span class="s">{" · ".join(bits)}</span></a>'
        )
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    return f"""<!DOCTYPE html>
<!-- Generated by PoGo_Links/scripts/publish.py on {stamp}. Don't edit by hand: changes are overwritten on the next publish. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<meta name="color-scheme" content="dark">
<title>PoGo Link Pages</title>
<link rel="icon" type="image/png" href="../img/favicon/favicon-32x32.png" sizes="32x32">
<style>
  /* Colours: Bart's VS Code palette, same as the link pages (page #2b2b29, cards #33332f, borders #404040,
     text #d1d5db, bold #e5e5e5, grey #9ca3af). Width capped at 412px (Pixel 6 Pro) like the pages. */
  html {{ background: #2b2b29; }}
  body {{ max-width: 412px; box-sizing: border-box; margin: 0 auto; padding: 16px; background: #2b2b29; color: #d1d5db;
         font-family: -apple-system, system-ui, sans-serif; }}
  h1 {{ font-size: 18px; margin: 0 0 12px; color: #e5e5e5; }}
  h1 .c {{ color: #9ca3af; font-weight: 400; font-size: 13px; margin-left: 6px; }}
  /* Every row spans the full width, so the cards line up edge to edge (Bart's symmetry rule). */
  .row {{ display: block; background: #33332f; border: 1px solid #404040; border-radius: 8px; padding: 10px 12px;
         margin-bottom: 8px; text-decoration: none; }}
  .row:active {{ background: #3a3a36; }}
  .t {{ display: block; color: #74aeea; font-weight: 700; font-size: 15px; }}
  .s {{ display: block; color: #9ca3af; font-size: 12px; margin-top: 3px; }}
  .foot {{ display: flex; justify-content: space-between; color: #9ca3af; font-size: 12px; margin-top: 14px; }}
  .foot a {{ color: #74aeea; }}
</style>
</head>
<body>
<h1>PoGo Link Pages<span class="c">{len(pages)} page{'s' if len(pages) != 1 else ''}</span></h1>
{chr(10).join(rows)}
<div class="foot"><a href="../">Home</a><span>Published {stamp}</span></div>
</body>
</html>
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-n", "--dry-run", action="store_true")
    ap.add_argument("--no-push", action="store_true")
    ap.add_argument("--src")
    a = ap.parse_args()

    src = find_source(a.src)
    # Several Macs, one repo: never publish onto a stale checkout (Bart's standing rule).
    git("fetch", "-q")
    ahead_behind = git("rev-list", "--left-right", "--count", "HEAD...@{u}").split()
    if ahead_behind[1] != "0":
        if git("status", "--porcelain") or a.dry_run:
            sys.exit("This checkout is behind GitHub. Pull first (git pull --ff-only).")
        git("pull", "-q", "--ff-only")

    # NFC names: macOS can hand out NFD, which git and the web would treat as a different file.
    wanted = {}
    for p in glob.glob(os.path.join(src, "*.html")):
        wanted[unicodedata.normalize("NFC", os.path.basename(p))] = p
    if not wanted:
        sys.exit(f"No .html pages in {src}; refusing to empty the site.")
    have = {unicodedata.normalize("NFC", f) for f in os.listdir(OUT) if f.endswith(".html") and f != "index.html"} \
        if os.path.isdir(OUT) else set()

    added, updated, removed = [], [], []
    for name, p in sorted(wanted.items()):
        dst = os.path.join(OUT, name)
        new = open(p, "rb").read()
        if name not in have:
            added.append(name)
        elif open(dst, "rb").read() != new:
            updated.append(name)
        else:
            continue
        if not a.dry_run:
            with open(dst, "wb") as f:
                f.write(new)
    for name in sorted(have - set(wanted)):
        removed.append(name)
        if not a.dry_run:
            os.remove(os.path.join(OUT, name))

    for label, names in (("Added", added), ("Updated", updated), ("Removed", removed)):
        for n in names:
            print(f"{label}: {n}")
    if a.dry_run:
        print("Dry run: nothing written." if added or updated or removed else "Nothing to publish.")
        return

    pages = sorted(((n, *page_info(wanted[n]), os.path.getmtime(wanted[n])) for n in wanted),
                   key=lambda t: t[3], reverse=True)
    index = os.path.join(OUT, "index.html")
    old = open(index, encoding="utf-8").read() if os.path.exists(index) else ""
    new_index = build_index(pages)
    # Ignore the generated timestamp when deciding whether the list changed.
    strip = lambda s: re.sub(r"(on|Published) \d{4}-\d\d-\d\d \d\d:\d\d", "", s)
    if strip(old) != strip(new_index):
        with open(index, "w", encoding="utf-8") as f:
            f.write(new_index)

    git("add", "-A", "PoGo_Links")
    if not git("status", "--porcelain", "PoGo_Links"):
        print("Nothing to publish: the site already matches Drive.")
        return
    parts = [f"{len(x)} {w}" for x, w in ((added, "added"), (updated, "updated"), (removed, "removed")) if x]
    git("commit", "-q", "-m", f"PoGo Links: publish ({', '.join(parts) or 'list refreshed'})")
    if a.no_push:
        print("Committed, not pushed (--no-push).")
        return
    git("push", "-q")
    print("Pushed. Live in a minute or two: https://bartmaneh.github.io/PoGo_Links/")


if __name__ == "__main__":
    main()
